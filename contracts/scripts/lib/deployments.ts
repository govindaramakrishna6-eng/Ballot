// Reads/writes frontend/src/contract/deployments.json and abi.ts — the single hand-off
// between the contracts project and the frontend.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";
import type { Abi, Address, Hash } from "viem";
import { CONTRACTS_DIR } from "./config.ts";

export const FRONTEND_CONTRACT_DIR = resolve(CONTRACTS_DIR, "../frontend/src/contract");
const DEPLOYMENTS_PATH = resolve(FRONTEND_CONTRACT_DIR, "deployments.json");
const ABI_PATH = resolve(FRONTEND_CONTRACT_DIR, "abi.ts");

export type Deployment = { address: Address; deployBlock: number; txHash: Hash; deployedAt: string };
export type Deployments = Record<string, Deployment>; // keyed by chainId (JSON keys are strings)

export function readDeployments(): Deployments {
  return existsSync(DEPLOYMENTS_PATH) ? JSON.parse(readFileSync(DEPLOYMENTS_PATH, "utf8")) : {};
}

export function deploymentFor(chainId: number): Deployment {
  const d = readDeployments()[String(chainId)];
  if (!d) {
    console.error(`No deployment for chainId ${chainId} in deployments.json. Deploy first.`);
    process.exit(1);
  }
  return d;
}

export function writeDeployment(chainId: number, deployment: Deployment): void {
  mkdirSync(FRONTEND_CONTRACT_DIR, { recursive: true });
  const all = { ...readDeployments(), [String(chainId)]: deployment };
  writeFileSync(DEPLOYMENTS_PATH, JSON.stringify(all, null, 2) + "\n");
}

export function readArtifact(): { abi: Abi; bytecode: `0x${string}` } {
  const path = resolve(CONTRACTS_DIR, "artifacts/contracts/VotingDApp.sol/VotingDApp.json");
  if (!existsSync(path)) {
    console.error("Artifact not found. Run `npm run compile:prod` first.");
    process.exit(1);
  }
  return JSON.parse(readFileSync(path, "utf8"));
}

/** `as const` keeps the ABI literal so wagmi/viem infer argument and return types. */
export function writeAbi(abi: Abi): void {
  mkdirSync(FRONTEND_CONTRACT_DIR, { recursive: true });
  writeFileSync(
    ABI_PATH,
    "// Generated by contracts/scripts/deploy.ts — do not edit by hand.\n" +
      `export const votingAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
}
